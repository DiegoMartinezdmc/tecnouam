CREATE TABLE IF NOT EXISTS equipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_patrimonial VARCHAR(255) NOT NULL UNIQUE,
    nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT ck_equipos_estado CHECK (estado IN ('DISPONIBLE', 'PRESTADO'))
);

CREATE TABLE IF NOT EXISTS prestamos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipo_id BIGINT NOT NULL REFERENCES equipos(id),
    nombre_solicitante VARCHAR(255) NOT NULL,
    fecha_prestamo DATE NOT NULL,
    fecha_prevista_devolucion DATE NOT NULL,
    estado VARCHAR(255) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_prestamos_estado CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    CONSTRAINT ck_prestamos_fechas CHECK (fecha_prevista_devolucion >= fecha_prestamo)
);

CREATE INDEX IF NOT EXISTS ix_prestamos_equipo_id ON prestamos(equipo_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_prestamo_activo_por_equipo ON prestamos(equipo_id) WHERE estado = 'ACTIVO';
